import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const uiDirectory = path.join(root, "src/shared/shadcn/ui");
const indexFile = path.join(root, "src/shared/shadcn/index.tsx");

const files = await readdir(uiDirectory);
const components = files
    .filter((file) => file.endsWith(".tsx"))
    .map((file) => file.replace(/\.tsx$/, ""))
    .toSorted((a, b) =>
        a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })
    );

const content = [
    "// Generated by `npm run shadcn:exports` — do not edit manually.",
    "",
    ...components.map((name) => `export * from "./ui/${name}";`),
    "",
].join("\n");

await writeFile(indexFile, content);
console.log(`Updated ${indexFile} (${components.length} components)`);
